/// Adhkar from «حصن المسلم» (سعيد بن علي بن وهف القحطاني). The texts are
/// the Prophet's ﷺ words as narrated in the hadith collections (public
/// domain); each carries a short source reference. Quranic passages come
/// from the Tanzil text (quran_passages.dart).
class Dhikr {
  const Dhikr(this.text, {this.count = 1, required this.source, this.note});
  final String text;
  final int count;
  final String source;

  /// Short usage note («بعد الفجر والمغرب ٣ مرات»…).
  final String? note;
}

class AdhkarCategory {
  const AdhkarCategory(this.id, this.title, this.subtitle, this.items);
  final String id;
  final String title;
  final String subtitle;
  final List<Dhikr> items;
}

