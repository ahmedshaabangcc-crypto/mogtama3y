/// The point's country when it is one of the 22 states, else null. When a
/// neighbour's rough box wins (Iran's covers Dammam), the smallest Arab box
/// that holds the point. SQL twin: private.arab_country_at() in 0093.
String? arabCountryAt(double lat, double lng) {
  final at = countryAt(lat, lng);
  if (isArabCountry(at)) return at;
  String? best;
  var bestArea = double.infinity;
  for (final (iso, a, b, c, d) in countryBoxes) {
    if (isArabCountry(iso) && lat >= a && lat <= b && lng >= c && lng <= d && (b - a) * (d - c) < bestArea) {
      bestArea = (b - a) * (d - c);
      best = iso;
    }
  }
  return best;
}

/// The division of a point: the nearest division capital (or extra point)
/// inside [country] (default: the point's own country via [arabCountryAt],
/// Egypt when it isn't in one of the 22).
String divisionAt(double lat, double lng, {String? country}) {
  var iso = country?.toUpperCase();
  if (!isArabCountry(iso)) iso = arabCountryAt(lat, lng) ?? 'EG';
  String? best;
  var bestD = double.infinity;
  for (final a in adminAreasOf(iso)) {
    for (final (la, ln) in [(a.lat, a.lng), ...a.extra]) {
      final d = (lat - la) * (lat - la) + (lng - ln) * (lng - ln);
      if (d < bestD) {
        bestD = d;
        best = a.name;
      }
    }
  }
  return best!;
}
