final _cache = <String, List<AdminArea>>{};

List<AdminArea> _parse(String s) => [
      for (final entry in s.split('|'))
        () {
          final i = entry.indexOf(':');
          final pts = [
            for (final p in entry.substring(i + 1).split(';'))
              () {
                final c = p.split(',');
                return (double.parse(c[0]), double.parse(c[1]));
              }(),
          ];
          return AdminArea(entry.substring(0, i), pts.first.$1, pts.first.$2, pts.sublist(1));
        }(),
    ];

/// ISO codes that have a division list (all 22).
Iterable<String> get adminAreaCountries => _data.keys;

/// Divisions of [iso] (Egypt's for null / unknown).
List<AdminArea> adminAreasOf(String? iso) {
  final k = _data.containsKey(iso?.toUpperCase()) ? iso!.toUpperCase() : 'EG';
  return _cache[k] ??= _parse(_data[k]!);
}

/// Names of the divisions of [iso] (Egypt's for null / unknown).
List<String> adminAreaNames(String? iso) => [for (final a in adminAreasOf(iso)) a.name];

/// «المحافظة» / «المنطقة» / «الإمارة»… — what a division is called there.
